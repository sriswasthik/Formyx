/**
 * Writes src/forms/phone-countries.ts: each country's calling code and the lengths its
 * national numbers come in, from libphonenumber-js's metadata. A small table instead of the
 * library keeps the public form light. Run after updating libphonenumber-js:
 *
 *   node packages/shared/scripts/phone-countries.mjs && pnpm exec prettier --write packages/shared/src/forms/phone-countries.ts
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { getCountries, getCountryCallingCode, Metadata } from 'libphonenumber-js/core';
import metadata from 'libphonenumber-js/metadata.max.json';

const plans = new Metadata(metadata);

/** The shortest and longest national numbers a country uses, from its numbering plan. */
function lengths(country) {
  plans.selectNumberingPlan(country);
  const possible = plans.numberingPlan.possibleLengths() ?? [];
  return possible.length > 0 ? [Math.min(...possible), Math.max(...possible)] : [4, 14];
}

const rows = getCountries(metadata)
  .map((country) => {
    const [min, max] = lengths(country);
    return `  ['${country}', '${getCountryCallingCode(country, metadata)}', ${min}, ${max}],`;
  })
  .join('\n');

const source = `// Generated by scripts/phone-countries.mjs from libphonenumber-js metadata. Do not edit.

/** [country (ISO 3166-1), calling code, shortest and longest national number]. */
export const PHONE_COUNTRY_TABLE: readonly (readonly [string, string, number, number])[] = [
${rows}
];
`;

const target = fileURLToPath(new URL('../src/forms/phone-countries.ts', import.meta.url));
await writeFile(target, source);
console.log(`Wrote ${getCountries(metadata).length} countries to ${target}`);
