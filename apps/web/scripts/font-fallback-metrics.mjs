/* eslint-disable no-console -- a command-line script: printing is its job. */
/**
 * Works out the resized local fallbacks for the theme fonts that were not measured by hand,
 * from the fonts' published metrics, and writes them to
 * src/features/form-renderer/theme/fallback-metrics.ts. Run it after adding a font:
 *
 *   node apps/web/scripts/font-fallback-metrics.mjs
 *
 * The maths is the one next/font uses: scale the local font so its average character width
 * matches, then set ascent and descent so lines keep their height.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import arial from '@capsizecss/metrics/arial';
import courierNew from '@capsizecss/metrics/courierNew';
import georgia from '@capsizecss/metrics/georgia';

const LOCALS = {
  Arial: arial,
  Georgia: georgia,
  'Courier New': courierNew,
};

/** Font id → [capsize metrics name, CSS family it declares, local font to resize]. */
const FONTS = {
  manrope: ['manrope', 'Manrope', 'Arial'],
  'plus-jakarta-sans': ['plusJakartaSans', 'Plus Jakarta Sans', 'Arial'],
  'work-sans': ['workSans', 'Work Sans', 'Arial'],
  figtree: ['figtree', 'Figtree', 'Arial'],
  outfit: ['outfit', 'Outfit', 'Arial'],
  'public-sans': ['publicSans', 'Public Sans', 'Arial'],
  sora: ['sora', 'Sora', 'Arial'],
  lora: ['lora', 'Lora', 'Georgia'],
  merriweather: ['merriweather', 'Merriweather', 'Georgia'],
  'libre-baskerville': ['libreBaskerville', 'Libre Baskerville', 'Georgia'],
  'crimson-pro': ['crimsonPro', 'Crimson Pro', 'Georgia'],
  literata: ['literata', 'Literata', 'Georgia'],
  'eb-garamond': ['ebGaramond', 'EB Garamond', 'Georgia'],
  newsreader: ['newsreader', 'Newsreader', 'Georgia'],
  syne: ['syne', 'Syne', 'Arial'],
  unbounded: ['unbounded', 'Unbounded', 'Arial'],
  'bodoni-moda': ['bodoniModa', 'Bodoni Moda', 'Georgia'],
  'dm-serif-display': ['dmSerifDisplay', 'DM Serif Display', 'Georgia'],
  quicksand: ['quicksand', 'Quicksand', 'Arial'],
  comfortaa: ['comfortaa', 'Comfortaa', 'Arial'],
  fredoka: ['fredoka', 'Fredoka', 'Arial'],
  'baloo-2': ['baloo2', 'Baloo 2', 'Arial'],
  kalam: ['kalam', 'Kalam', 'Arial'],
  'patrick-hand': ['patrickHand', 'Patrick Hand', 'Arial'],
  caveat: ['caveat', 'Caveat', 'Arial'],
  'dancing-script': ['dancingScript', 'Dancing Script', 'Arial'],
  'jetbrains-mono': ['jetbrainsMono', 'JetBrains Mono', 'Courier New'],
  'ibm-plex-mono': ['ibmPlexMono', 'IBM Plex Mono', 'Courier New'],
  'roboto-mono': ['robotoMono', 'Roboto Mono', 'Courier New'],
  'source-code-pro': ['sourceCodePro', 'Source Code Pro', 'Courier New'],
  'fira-code': ['firaCode', 'Fira Code', 'Courier New'],
  'space-mono': ['spaceMono', 'Space Mono', 'Courier New'],
};

const round = (value) => Math.round(value * 10_000) / 100;
const widthPerEm = (metrics) =>
  (metrics.subsets?.latin?.xWidthAvg ?? metrics.xWidthAvg) / metrics.unitsPerEm;

const entries = [];
for (const [id, [metricsName, family, local]] of Object.entries(FONTS)) {
  const { default: metrics } = await import(`@capsizecss/metrics/${metricsName}`);
  const sizeAdjust = widthPerEm(metrics) / widthPerEm(LOCALS[local]);
  entries.push(
    `  ${/^[a-z]+$/.test(id) ? id : `'${id}'`}: {\n` +
      `    family: '${family} Fallback',\n` +
      `    local: '${local}',\n` +
      `    sizeAdjust: ${round(sizeAdjust)},\n` +
      `    ascent: ${round(metrics.ascent / metrics.unitsPerEm / sizeAdjust)},\n` +
      `    descent: ${round(Math.abs(metrics.descent) / metrics.unitsPerEm / sizeAdjust)},\n` +
      `  },`,
  );
}

const source = `// Generated by scripts/font-fallback-metrics.mjs from @capsizecss/metrics. Do not edit.
import type { FallbackFace } from './font-fallbacks';

export const COMPUTED_FALLBACKS = {
${entries.join('\n')}
} as const satisfies Record<string, FallbackFace & { family: string }>;
`;

const target = fileURLToPath(
  new URL('../src/features/form-renderer/theme/fallback-metrics.ts', import.meta.url),
);
await writeFile(target, source);
console.log(`Wrote ${entries.length} fallbacks to ${target}`);
